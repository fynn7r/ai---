/**
 * 图片识别的上限口径。前后端共用同一组常量：
 * 前端要按它决定「一次能选几张」「超了怎么提示」，服务端要按它拒绝请求。
 * 两处各写一个数字，迟早会出现「提示说 3 张，实际只收 2 张」。
 */

/** 一次请求最多识别几张。三张足够覆盖「一张主通知 + 两页附件」。 */
export const OCR_MAX_FILES = 3;

/** 单张图上限。手机原图通常 2–4 MB，5 MB 已能覆盖绝大多数截图与翻拍。 */
export const OCR_MAX_FILE_BYTES = 5 * 1024 * 1024;

/** 一次请求的总上限。base64 内联会放大三分之一，留出余量后仍可控。 */
export const OCR_MAX_TOTAL_BYTES = 12 * 1024 * 1024;
